import 'dart:convert';

import 'lzstring.dart';
import 'models.dart';

class IbomParseException implements Exception {
  IbomParseException(this.message);
  final String message;
  @override
  String toString() => message;
}

final _lcscPattern = RegExp(r'C\d{3,}', caseSensitive: false);

/// Extracts the first LCSC part number (`C25803`) from a field value.
String? extractLcscNumber(String? text) {
  if (text == null) return null;
  final m = _lcscPattern.firstMatch(text);
  return m?.group(0)!.toUpperCase();
}

/// The BOM read out of an InteractiveHtmlBom page.
class ParsedBom {
  ParsedBom({
    required this.title,
    required this.revision,
    required this.items,
    required this.lcscField,
  });

  final String title;
  final String revision;
  final List<BomItem> items;

  /// The ibom field that held LCSC numbers, or null when none was found.
  final String? lcscField;
}

/// Parses an ibom.html generated by InteractiveHtmlBom 2.4 or newer.
ParsedBom parseIbomHtml(String html) {
  final pcbdata = _extractPcbdata(html);
  final config = _extractConfig(html);

  final bom = pcbdata['bom'];
  if (bom is! Map || bom['both'] is! List || bom['fields'] == null) {
    throw IbomParseException(
      'ibom.html 沒有 BOM 欄位資料，請用 InteractiveHtmlBom 2.4 以上版本重新產生。',
    );
  }

  final fieldNames = [
    for (final f in (config['fields'] as List?) ?? const []) f.toString(),
  ];
  final fields = bom['fields'];
  List<String> fieldsOf(int fpIndex) {
    final Object? row = fields is Map
        ? fields['$fpIndex']
        : (fields is List && fpIndex < fields.length ? fields[fpIndex] : null);
    if (row is! List) return const [];
    return [for (final v in row) v?.toString() ?? ''];
  }

  final skipped = {
    for (final s in (bom['skipped'] as List?) ?? const []) (s as num).toInt(),
  };

  // Each group is a list of [ref, footprintIndex].
  final groups = <List<(String, int)>>[];
  for (final group in bom['both'] as List) {
    if (group is! List || group.isEmpty || group.first is! List) {
      throw IbomParseException(
        'ibom.html 的 BOM 格式太舊，請用 InteractiveHtmlBom 2.4 以上版本重新產生。',
      );
    }
    final refs = <(String, int)>[
      for (final r in group)
        if (!skipped.contains((r[1] as num).toInt()))
          (r[0].toString(), (r[1] as num).toInt()),
    ];
    if (refs.isNotEmpty) groups.add(refs);
  }

  final lcscCol = _findLcscColumn(fieldNames, groups, fieldsOf);
  final mpnCol = _findColumn(
    fieldNames,
    RegExp(
      r'^(mpn|mfr\.? ?(part|p/?n|#)?|manufacturer ?part( ?number)?|part ?number|mfg ?p/?n)$',
      caseSensitive: false,
    ),
    exclude: lcscCol,
  );
  final valueCol = _findColumn(
    fieldNames,
    RegExp(r'^value$', caseSensitive: false),
  );
  final footprintCol = _findColumn(
    fieldNames,
    RegExp(r'^footprint$', caseSensitive: false),
  );

  String col(List<String> row, int? i) =>
      (i != null && i < row.length) ? row[i].trim() : '';

  final byKey = <String, _ItemBuilder>{};
  for (final group in groups) {
    final row = fieldsOf(group.first.$2);
    final lcsc = lcscCol == null ? null : extractLcscNumber(col(row, lcscCol));
    final value = col(row, valueCol);
    final footprint = col(row, footprintCol);
    final key = lcsc ?? '$value|$footprint';
    final b = byKey.putIfAbsent(key, () => _ItemBuilder(key, lcsc));
    b.refs.addAll(group.map((r) => r.$1));
    b.addDistinct(b.values, value);
    b.addDistinct(b.footprints, footprint);
    b.addDistinct(b.mpns, col(row, mpnCol));
  }

  final metadata = pcbdata['metadata'] as Map? ?? const {};
  return ParsedBom(
    title: metadata['title']?.toString() ?? '',
    revision: metadata['revision']?.toString() ?? '',
    items: [for (final b in byKey.values) b.build()],
    lcscField: lcscCol == null ? null : fieldNames[lcscCol],
  );
}

class _ItemBuilder {
  _ItemBuilder(this.key, this.lcsc);
  final String key;
  final String? lcsc;
  final refs = <String>[];
  final values = <String>[];
  final footprints = <String>[];
  final mpns = <String>[];

  void addDistinct(List<String> list, String v) {
    if (v.isNotEmpty && !list.contains(v)) list.add(v);
  }

  BomItem build() => BomItem(
    key: key,
    lcsc: lcsc,
    refs: refs.toSet().toList()..sort(compareRefs),
    values: values,
    footprints: footprints,
    mpns: mpns,
  );
}

/// Natural order for references: R2 before R10.
int compareRefs(String a, String b) {
  final re = RegExp(r'^(\D*)(\d*)(.*)$');
  final ma = re.firstMatch(a)!;
  final mb = re.firstMatch(b)!;
  final p = ma.group(1)!.compareTo(mb.group(1)!);
  if (p != 0) return p;
  final na = int.tryParse(ma.group(2)!) ?? -1;
  final nb = int.tryParse(mb.group(2)!) ?? -1;
  if (na != nb) return na.compareTo(nb);
  return ma.group(3)!.compareTo(mb.group(3)!);
}

int? _findColumn(List<String> names, RegExp pattern, {int? exclude}) {
  for (var i = 0; i < names.length; i++) {
    if (i != exclude && pattern.hasMatch(names[i].trim())) return i;
  }
  return null;
}

/// A column named like LCSC / JLCPCB part, else the column whose values look
/// most like LCSC numbers.
int? _findLcscColumn(
  List<String> names,
  List<List<(String, int)>> groups,
  List<String> Function(int) fieldsOf,
) {
  for (var i = 0; i < names.length; i++) {
    final n = names[i].toLowerCase();
    if (n.contains('lcsc') ||
        n.contains('jlc') ||
        n.contains('supplier part')) {
      return i;
    }
  }
  int? best;
  var bestHits = 0;
  for (var i = 0; i < names.length; i++) {
    var hits = 0;
    for (final g in groups) {
      final row = fieldsOf(g.first.$2);
      if (i < row.length && RegExp(r'^\s*C\d{3,}\s*$').hasMatch(row[i])) hits++;
    }
    if (hits > bestHits) {
      bestHits = hits;
      best = i;
    }
  }
  return best;
}

Map<String, dynamic> _extractPcbdata(String html) {
  const marker = 'var pcbdata = ';
  final start = html.indexOf(marker);
  if (start < 0) {
    throw IbomParseException(
      '這不是 InteractiveHtmlBom 產生的 ibom.html（找不到 pcbdata）。',
    );
  }
  final rest = html.substring(start + marker.length);
  final compressed = RegExp(
    r'^JSON\.parse\(LZString\.decompressFromBase64\("([^"]*)"\)\)',
  ).firstMatch(rest);
  String json;
  if (compressed != null) {
    final decoded = lzDecompressFromBase64(compressed.group(1)!);
    if (decoded == null || decoded.isEmpty) {
      throw IbomParseException('ibom.html 的 pcbdata 解壓縮失敗。');
    }
    json = decoded;
  } else {
    final end = rest.indexOf('\n');
    json = (end < 0 ? rest : rest.substring(0, end)).trim();
    if (json.endsWith(';')) json = json.substring(0, json.length - 1);
  }
  try {
    return jsonDecode(json) as Map<String, dynamic>;
  } on FormatException {
    throw IbomParseException('ibom.html 的 pcbdata 不是有效的 JSON。');
  }
}

Map<String, dynamic> _extractConfig(String html) {
  final m = RegExp(
    r'var config = (\{.*\})\s*;?\s*$',
    multiLine: true,
  ).firstMatch(html);
  if (m == null) return const {};
  try {
    return jsonDecode(m.group(1)!) as Map<String, dynamic>;
  } on FormatException {
    return const {};
  }
}
